
public class Main {
	
	public static void main(String[] args) {
		int num1 = 10;
		int num2 = 20;
		
		// Subtração
		System.out.println(num2 - num1);

		// Soma
		System.out.println(num2 + num1);

		// Divisão
		System.out.println(num2 / num1);

		// Multiplicação
		System.out.println(num2 * num1);

		// Resto
		System.out.println(num2 % num1);
	}
}
