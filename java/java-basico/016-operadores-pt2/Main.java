
public class Main {

	public static void main(String[] args) {
		int a = 10;
		int b = 20;

		// Menor que 
		System.out.println("10 < 20? " + (a < b));
		
		// Maior que
		System.out.println("10 > 20? " + (a > b));

		// Menor ou igual a
		System.out.println("10 <= 20? " + (a <= b));

		// Maior ou igual a
		System.out.println("10 >= 20? " + (a >= b));

		// Igual a
		System.out.println("10 == 20? " + (a == b));

		// Diferente
		System.out.println("10 != 20? " + (a != b));
	}
}
