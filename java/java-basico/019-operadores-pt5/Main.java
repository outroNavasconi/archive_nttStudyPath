
public class Main {

	public static void main(String[] args) {
		// Atribuição (=)
		
		double bonus = 1800.78;
		System.out.println(bonus);

		// bonus = bonus + 1000
		bonus += 1000;
		System.out.println(bonus);

		// bonus = bonus - 500
		bonus -= 500;
		System.out.println(bonus);

		// bonus = bonus * 2
		bonus *= 2;
		System.out.println(bonus);

		// bonus = bonus % 2
		bonus %= 2;
		System.out.println(bonus);

		int contador = 1;
		
		// contador = contador + 1
		// contador += 1
		contador++;
		System.out.println(contador);

		// contador = contador - 1
		// contador -= 1
		contador--;
		System.out.println(contador);

		// --contador
		// ++contador
	}
}
