
public class Main {

	public static void main(String[] args) {
		byte byt = 127;
		short sht = 32767;
		int itr = 2147483647;
		long lng = 287628762867218728712123;
		System.out.println("\t. byte (" + byt + ")");
		System.out.println("\t. short (" + sht + ")");
		System.out.println("\t. int (" + itr + ")");
		System.out.println("\t. long (" + lng + ")");

		float flt = 1.23;
		double dbl = 2.46;
		System.out.println("\t. float (" + flt + ")");
		System.out.println("\t. double (" + dbl + ")");

		char chr = 'a';
		System.out.println("\t. char (" + chr + ")");

		boolean bol = true;
		System.out.println("\t. boolean (" + bol + ")");
	}
}
